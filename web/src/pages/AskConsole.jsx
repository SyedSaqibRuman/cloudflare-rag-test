import { useEffect, useRef, useState } from "react";
import { askStream, resetAskCache, listAssistants, getAskSuggestions } from "../api";
import { useCompanies } from "../context";
import { Button, Badge, ErrorBanner } from "../components/ui";
import Markdown from "../components/Markdown";
import { useHeaderActions } from "../components/Layout";

const fmtMs = (ms) => (ms == null ? "—" : ms < 1000 ? `${Math.round(ms)}ms` : `${(ms / 1000).toFixed(2)}s`);
const fmtNum = (n) => n.toLocaleString();

// Fallback starter questions — used when the per-company KB-generated
// suggestions aren't available (no credentials, empty index, or API failure).
// Static fallback shown only while KB-generated questions load (or when the
// company has no usable KB). Deliberately content-agnostic — the KB-specific
// questions come from /ask/suggestions, which reads the bound KB's chunks.
const FALLBACK_STARTERS = [
  "What topics does this knowledge base cover?",
  "Summarize the main points of this content.",
  "What key terms are defined here?",
  "Give me an example from this content.",
];

// KB-generated starters cost a small-LLM call, so cache them per company in
// localStorage for 24h instead of regenerating on every page load.
const STARTERS_CACHE_TTL = 24 * 60 * 60 * 1000;

function loadCachedStarters(key) {
  try {
    const raw = localStorage.getItem(key);
    if (!raw) return null;
    const { ts, questions } = JSON.parse(raw);
    if (!ts || Date.now() - ts > STARTERS_CACHE_TTL) return null;
    return Array.isArray(questions) && questions.length ? questions : null;
  } catch {
    return null;
  }
}

function saveCachedStarters(key, questions) {
  try {
    localStorage.setItem(key, JSON.stringify({ ts: Date.now(), questions }));
  } catch {
    /* storage full/unavailable — cache is best-effort */
  }
}

export default function AskConsole() {
  const { company, companies } = useCompanies();
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState("");
  const [streaming, setStreaming] = useState(false);
  const [error, setError] = useState(null);
  const [apiKey, setApiKey] = useState("");
  const [resetting, setResetting] = useState(false);
  const [live, setLive] = useState(null);
  const [last, setLast] = useState(null);
  const [session, setSession] = useState({ requests: 0, tokens: 0, ttfbSum: 0, ttfbCount: 0 });
  const [assistants, setAssistants] = useState([]);
  const [selectedAssistant, setSelectedAssistant] = useState("");
  const abortRef = useRef(null);
  const bottomRef = useRef(null);
  const inputRef = useRef(null);
  const [starters, setStarters] = useState(FALLBACK_STARTERS);
  const startRef = useRef(0);
  const firstTokenRef = useRef(null);
  const tokenCountRef = useRef(0);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, streaming]);

  useEffect(() => {
    // restore the per-company ask API key so it survives page reloads
    setApiKey(localStorage.getItem(`ask-api-key:${company || ""}`) || "");
    setSelectedAssistant(""); // reset when company changes
  }, [company]);

  // Load assistants for the selected company
  useEffect(() => {
    if (!company) { setAssistants([]); return; }
    listAssistants(company).then((r) => setAssistants(r.items ?? [])).catch(() => setAssistants([]));
  }, [company]);

  // Load KB-generated starter questions (cached 24h per company, fallback
  // static). Re-runs when the API key changes (debounced) so key-gated
  // companies get KB-aware starters once the user pastes their key.
  useEffect(() => {
    if (!company) {
      setStarters(FALLBACK_STARTERS);
      return;
    }
    // v2 — flushes 24h-cached starters generated by the old company-framed
    // prompt (which could be off-KB, e.g. certification questions for a book KB).
    const cacheKey = `ask-starters:v2:${company}`;
    const cached = loadCachedStarters(cacheKey);
    if (cached) {
      setStarters(cached);
      return;
    }
    setStarters(FALLBACK_STARTERS); // show static instantly, upgrade when KB questions arrive
    let cancelled = false;
    const timer = setTimeout(() => {
      getAskSuggestions(company, apiKey || undefined)
        .then((questions) => {
          if (cancelled) return;
          const list = Array.isArray(questions) && questions.length ? questions.slice(0, 4) : FALLBACK_STARTERS;
          setStarters(list);
          if (list !== FALLBACK_STARTERS) saveCachedStarters(cacheKey, list);
        })
        .catch(() => {
          if (!cancelled) setStarters(FALLBACK_STARTERS);
        });
    }, 600);
    return () => {
      cancelled = true;
      clearTimeout(timer);
    };
  }, [company, apiKey]);

  // persist per company — the key is restored on company switch / reload
  const setApiKeyForCompany = (value) => {
    setApiKey(value);
    try {
      localStorage.setItem(`ask-api-key:${company || ""}`, value);
    } catch {
      /* storage full/unavailable — persistence is best-effort */
    }
  };

  const send = async (override) => {
    const question = (override ?? input).trim();
    if (!question || streaming) return;
    if (!company) {
      setError("Select a company in the sidebar before asking a question.");
      return;
    }

    setError(null);
    const userMsg = { role: "user", content: question };
    const assistantMsg = { role: "assistant", content: "", streaming: true };
    const draftIdx = messages.length + 1;
    setMessages((m) => [...m, userMsg, assistantMsg]);
    setInput("");
    setStreaming(true);

    const history = messages
      .filter((m) => !(m.role === "assistant" && m.streaming))
      .map((m) => ({ role: m.role, content: m.content }));

    const controller = new AbortController();
    abortRef.current = controller;

    startRef.current = performance.now();
    firstTokenRef.current = null;
    tokenCountRef.current = 0;
    setLive({ ttfbMs: null, tokens: 0 });

    let started = false;

    try {
      await askStream({
        question,
        history,
        company,
        apiKey: apiKey || undefined,
        assistantKey: selectedAssistant || undefined,
        signal: controller.signal,
        onToken: (token) => {
          if (!started) {
            started = true;
            setMessages((m) => m.map((msg, i) => (i === draftIdx ? { ...msg, content: "" } : msg)));
          }
          if (firstTokenRef.current === null) firstTokenRef.current = performance.now();
          tokenCountRef.current += 1;
          setLive({ ttfbMs: firstTokenRef.current - startRef.current, tokens: tokenCountRef.current });
          setMessages((m) =>
            m.map((msg, i) => (i === draftIdx ? { ...msg, content: msg.content + token, streaming: true } : msg))
          );
        },
        onStart: ({ sources, matches, graph }) => {
          setMessages((m) =>
            m.map((msg, i) =>
              i === draftIdx ? { ...msg, sources, matches, graph } : msg
            )
          );
        },
        onPossibleQuestions: (questions) => {
          setMessages((m) =>
            m.map((msg, i) => (i === draftIdx ? { ...msg, possibleQuestions: questions } : msg))
          );
        },
        onError: (errMsg) => {
          setMessages((m) => m.map((msg, i) => (i === draftIdx ? { ...msg, content: `Error: ${errMsg}`, streaming: false } : msg)));
        },
      });
    } catch (e) {
      if (e.name !== "AbortError") {
        setMessages((m) => m.map((msg, i) => (i === draftIdx ? { ...msg, content: `Error: ${e.message}`, streaming: false } : msg)));
      }
    } finally {
      setMessages((m) => m.map((msg, i) => (i === draftIdx ? { ...msg, streaming: false } : msg)));
      setStreaming(false);
      abortRef.current = null;

      const totalMs = performance.now() - startRef.current;
      const ttfbMs = firstTokenRef.current ? firstTokenRef.current - startRef.current : null;
      const tokens = tokenCountRef.current;
      setLast({ ttfbMs, totalMs, tokens });
      setLive(null);
      setSession((s) => ({
        requests: s.requests + 1,
        tokens: s.tokens + tokens,
        ttfbSum: s.ttfbSum + (ttfbMs ?? 0),
        ttfbCount: s.ttfbCount + (ttfbMs != null ? 1 : 0),
      }));

      setTimeout(() => inputRef.current?.focus(), 50);
    }
  };

  const stop = () => {
    abortRef.current?.abort();
  };

  const clear = () => {
    if (streaming) return;
    setMessages([]);
    setError(null);
  };

  const resetSession = () => {
    setSession({ requests: 0, tokens: 0, ttfbSum: 0, ttfbCount: 0 });
    setLast(null);
    setLive(null);
  };

  const resetConversation = async () => {
    if (streaming) return;
    setError(null);
    setResetting(true);
    try {
      if (company) await resetAskCache(company, apiKey || undefined);
      setMessages([]);
      resetSession();
    } catch (e) {
      setError(`Conversation reset failed: ${e.message}`);
    } finally {
      setResetting(false);
    }
  };

  const avgTtfb = session.ttfbCount ? session.ttfbSum / session.ttfbCount : null;


  useHeaderActions(
    <div className="flex max-w-full flex-wrap items-center justify-end gap-2">
      <Badge tone={company ? "green" : "amber"}>{company ? `Company: ${company}` : "No company selected"}</Badge>
      {assistants.length > 0 && (
        <select
          value={selectedAssistant}
          onChange={(e) => setSelectedAssistant(e.target.value)}
          className="rounded-lg border border-slate-700 bg-slate-950 px-2 py-1.5 text-xs text-slate-100 focus:border-indigo-500 focus:outline-none focus:ring-1 focus:ring-indigo-500"
          title="Select an assistant persona (optional)"
        >
          <option value="">Default assistant</option>
          {assistants.map((a) => (
            <option key={a.id} value={a.assistant_key}>{a.assistant_name}</option>
          ))}
        </select>
      )}
      {company && (
        <input
          type="password"
          placeholder="API key"
          aria-label="API key for selected company"
          value={apiKey}
          onChange={(e) => setApiKeyForCompany(e.target.value)}
          autoComplete="off"
          className="ml-auto w-full max-w-64 min-w-0 sm:ml-0 sm:w-64 rounded-lg border border-slate-700 bg-slate-950 px-3 py-1.5 text-xs text-slate-100 placeholder:text-slate-500 focus:border-indigo-500 focus:outline-none focus:ring-1 focus:ring-indigo-500"
        />
      )}
      <Button variant="ghost" onClick={clear} disabled={streaming || messages.length === 0} title="Clear the chat view (keeps the server answer cache)" className="whitespace-nowrap">
        Clear
      </Button>
      <Button
        variant="secondary"
        onClick={resetConversation}
        disabled={streaming || resetting}
        title="Reset the conversation: clear the chat and purge this company's server-side answer cache"
        className="whitespace-nowrap"
      >
        {resetting ? "Resetting…" : "Reset"}
      </Button>
    </div>
  );

  return (
    <div className="flex h-[calc(100vh-4.5rem)] flex-col space-y-4">

      <ErrorBanner message={error} onDismiss={() => setError(null)} />

      {/* Metrics bar — shown below header when data is available */}
      {(live || last || session.requests > 0) && (
        <div className="flex flex-wrap items-center gap-2 text-xs">
          {(live || last) && (
            <Badge tone={live ? "indigo" : "slate"} className="tabular-nums">
              {live ? (
                <>
                  <span className="text-slate-400">TTFB</span> {fmtMs(live.ttfbMs)}
                  <span className="text-slate-400">·</span> {fmtNum(live.tokens)} tok
                </>
              ) : (
                <>
                  <span className="text-slate-400">TTFB</span> {fmtMs(last.ttfbMs)}
                  <span className="text-slate-400">·</span> {fmtMs(last.totalMs)}
                  <span className="text-slate-400">·</span> {fmtNum(last.tokens)} tok
                </>
              )}
            </Badge>
          )}
          {session.requests > 0 && (
            <Badge tone="cyan" className="tabular-nums">
              <span className="text-slate-400">Σ</span> {session.requests} req · {fmtNum(session.tokens)} tok · avg {fmtMs(avgTtfb)}
              <button
                type="button"
                onClick={resetSession}
                title="Reset session stats"
                aria-label="Reset session stats"
                className="ml-0.5 rounded-full px-1 text-slate-500 transition-colors hover:bg-slate-700 hover:text-slate-100"
              >
                ×
              </button>
            </Badge>
          )}
        </div>
      )}

      <div role="log" aria-live="polite" className="flex-1 overflow-y-auto rounded-xl border border-slate-800 bg-slate-900/70 p-5">
        {messages.length === 0 ? (
          <div className="flex h-full flex-col items-center justify-center text-center">
            <div className="mb-4 flex h-16 w-16 items-center justify-center rounded-2xl bg-indigo-500/15 text-indigo-300">
              <svg className="h-8 w-8" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"><path d="M21 15a2 2 0 0 1-2 2H7l-4 4V5a2 2 0 0 1 2-2h14a2 2 0 0 1 2 2z" /></svg>
            </div>
            <p className="text-sm font-medium text-slate-300">Ask anything about the selected company</p>
            <p className="mt-1 max-w-sm text-xs text-slate-500">
              Questions are answered using the company's vector knowledge base, hybrid search, and its configured LLM.
            </p>
            {company && (
              <div className="mt-6">
                <p className="text-[10px] font-semibold uppercase tracking-wider text-slate-500">Try asking</p>
                <div className="mt-2 flex max-w-md flex-wrap justify-center gap-1.5">
                  {starters.map((q) => (
                    <button
                      key={q}
                      type="button"
                      onClick={() => send(q)}
                      disabled={streaming}
                      className="rounded-lg border border-slate-700 bg-slate-900 px-2.5 py-1 text-left text-xs text-slate-300 transition-colors hover:border-indigo-500 hover:text-indigo-200 disabled:cursor-not-allowed disabled:opacity-60"
                    >
                      {q}
                    </button>
                  ))}
                </div>
              </div>
            )}
          </div>
        ) : (
          <div className="space-y-5">
            {messages.map((msg, i) =>
              msg.role === "user" ? (
                <div key={i} className="flex justify-end">
                  <div className="max-w-[75%] break-words rounded-2xl rounded-br-sm bg-indigo-500/20 border border-indigo-500/30 px-4 py-2.5 text-sm text-slate-100">
                    {msg.content}
                  </div>
                </div>
              ) : (
                <div key={i} className="flex justify-start">
                  <div className="max-w-[85%] break-words rounded-2xl rounded-bl-sm bg-slate-950 border border-slate-800 px-4 py-3">
                    {msg.streaming && msg.content === "" && !msg.sources?.length && (
                      <span className="inline-flex gap-1">
                        <span className="h-1.5 w-1.5 animate-bounce rounded-full bg-indigo-400" />
                        <span className="h-1.5 w-1.5 animate-bounce rounded-full bg-indigo-400 [animation-delay:0.15s]" />
                        <span className="h-1.5 w-1.5 animate-bounce rounded-full bg-indigo-400 [animation-delay:0.3s]" />
                      </span>
                    )}
                    {msg.content !== "" && <Markdown text={msg.content} />}

                    {msg.sources?.length > 0 && msg.content !== "" && (
                      <div className="mt-3 border-t border-slate-800 pt-2.5">
                        <p className="mb-1.5 text-[10px] font-semibold uppercase tracking-wider text-slate-500">Sources</p>
                        <ol className="space-y-1">
                          {msg.sources.map((s, si) => (
                            <li key={si} className="flex items-baseline gap-2 text-xs text-slate-400">
                              <span className="shrink-0 rounded bg-slate-800 px-1.5 py-0.5 font-mono text-[10px] text-slate-300">
                                {typeof s.score === "number" ? s.score.toFixed(2) : "—"}
                              </span>
                              <span className="line-clamp-1">{s.title || "Untitled"}</span>
                            </li>
                          ))}
                        </ol>
                      </div>
                    )}

                    {msg.graph?.cypher && msg.content !== "" && (
                      <div className="mt-2 border-t border-slate-800 pt-2.5">
                        <p className="mb-1 text-[10px] font-semibold uppercase tracking-wider text-slate-500">Graph Knowledge</p>
                        <pre className="overflow-x-auto rounded bg-slate-950 p-2 text-[11px] text-slate-400">{msg.graph.cypher}</pre>
                        {msg.graph.context && (
                          <p className="mt-1 text-xs text-slate-500">{msg.graph.context}</p>
                        )}
                      </div>
                    )}

                    {msg.possibleQuestions?.length > 0 && !msg.streaming && (
                      <div className="mt-3 border-t border-slate-800 pt-2.5">
                        <p className="mb-1.5 text-[10px] font-semibold uppercase tracking-wider text-slate-500">Suggested questions</p>
                        <div className="flex flex-wrap gap-1.5">
                          {msg.possibleQuestions.map((q, qi) => (
                            <button
                              key={qi}
                              type="button"
                              onClick={() => send(q)}
                              disabled={streaming}
                              className="rounded-lg border border-slate-700 bg-slate-900 px-2.5 py-1 text-left text-xs text-slate-300 transition-colors hover:border-indigo-500 hover:text-indigo-200 disabled:cursor-not-allowed disabled:opacity-60"
                            >
                              {q}
                            </button>
                          ))}
                        </div>
                      </div>
                    )}
                  </div>
                </div>
              )
            )}
            <div ref={bottomRef} />
          </div>
        )}
      </div>

      <div className="rounded-xl border border-slate-800 bg-slate-900/70 p-3">
        <div className="flex items-end gap-2">
          <textarea
            ref={inputRef}
            aria-label="Your question"
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === "Enter" && !e.shiftKey) {
                e.preventDefault();
                send();
              }
            }}
            rows={2}
            placeholder="Type a question and press Enter…"
            className="flex-1 resize-none rounded-lg bg-slate-950 border border-slate-700 px-3 py-2.5 text-sm text-slate-100 placeholder:text-slate-500 focus:outline-none focus:border-indigo-500"
          />
          {streaming ? (
            <Button variant="danger" onClick={stop}>
              Stop
            </Button>
          ) : (
            <Button onClick={() => send()} disabled={!input.trim() || !company}>
              Send
            </Button>
          )}
        </div>
        <p className="mt-2 text-[11px] text-slate-500">
          {companies.length === 0
            ? "No companies available — create one in the Companies page first."
            : "Streaming via SSE · enter to send · shift+enter for newline"}
        </p>
      </div>
    </div>
  );
}
